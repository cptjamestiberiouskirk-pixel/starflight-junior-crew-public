export function formatPlayerQuestionLine(
  templateText: string,
  subjectAsked: string,
): string {
  let replacement = 'general things';
  const subLower = subjectAsked.toLowerCase().trim();
  if (subLower.includes('ancient')) {
    replacement = 'the Ancients';
  } else if (subLower.includes('empire')) {
    replacement = 'the Old Empire';
  } else if (subLower.includes('other')) {
    replacement = 'other races';
  } else if (subLower.includes('themsel') || subLower.includes('yourself')) {
    replacement = 'yourselves';
  } else if (subLower.includes('general') || subLower.includes('info')) {
    replacement = 'general things';
  }

  // Replace / with topic replacement
  let res = templateText.replace(/\//g, replacement);

  // Remove parentheses around filled clause
  res = res.replace(/\(([^)]*)\)/g, '$1');

  return res;
}

export function selectPlayerCommLine(
  subject: number,
  playerPosture: string | number,
  usageTracker: Record<number, number> = globalCommLineUsage,
  captainName = 'Commander',
  shipName = 'Explorer',
  questionTopic?: string,
): { line: ParsedCommLine; formattedText: string; id: number } {
  let postureCode = 1;
  if (subject === 3 || subject === 4 || subject === 15) {
    postureCode = 1;
  } else {
    const postStr = typeof playerPosture === 'string' ? playerPosture.toLowerCase() : '';
    if (postStr === 'obsequious' || playerPosture === 4) {
      postureCode = 4;
    } else if (postStr === 'hostile' || playerPosture === 3) {
      postureCode = 3;
    } else {
      postureCode = 2; // Friendly or Neutral default
    }
  }

  let pool = PARSED_COMM_LINES.filter(
    (l) => l.race === 16 && l.subject === subject && l.posture === postureCode,
  );
  if (pool.length === 0) {
    pool = PARSED_COMM_LINES.filter((l) => l.race === 16 && l.subject === subject);
  }
  if (pool.length === 0) {
    pool = PARSED_COMM_LINES.filter((l) => l.race === 16);
  }

  let best = pool[0];
  let minCount = usageTracker[best.id] || 0;
  for (let i = 1; i < pool.length; i++) {
    const cand = pool[i];
    const cCount = usageTracker[cand.id] || 0;
    if (cCount < minCount) {
      minCount = cCount;
      best = cand;
    }
  }

  usageTracker[best.id] = (usageTracker[best.id] || 0) + 1;
  globalCommLineUsage[best.id] = (globalCommLineUsage[best.id] || 0) + 1;

  let text = best.text;
  if (subject === 14 && questionTopic) {
    text = formatPlayerQuestionLine(text, questionTopic);
  }
  text = text.replace(/\*/g, captainName);
  text = text.replace(/&/g, shipName);

  return {
    line: best,
    formattedText: text,
    id: best.id,
  };
}

export function formatCommText(
  text: string,
  captainName = 'Commander',
  shipName = 'Explorer',
  alienCommander = 'Commander',
  alienShip = 'Vessel',
  paramX?: string,
  paramY?: string,
): string {
  let res = text;
  res = res.replace(/\*/g, captainName);
  res = res.replace(/&/g, shipName);
  res = res.replace(/%/g, alienCommander);
  res = res.replace(/\+/g, alienShip);
  res = res.replace(/{SHIP}/g, shipName);
  res = res.replace(/{CAPTAIN}/g, captainName);
  if (paramX !== undefined) {
    res = res.replace(/\bX\b/g, paramX);
  }
  if (paramY !== undefined) {
    res = res.replace(/\bY\b/g, paramY);
  }
  return res;
}

export const globalCommLineUsage: Record<number, number> = {};

