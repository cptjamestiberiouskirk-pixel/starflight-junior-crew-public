export function parseCommLine(rawLine: string, index = 0): ParsedCommLine {
  const parts = rawLine.split('|');
  const original = originalCommRules[parts[0]];
  return {
    id: parseInt(parts[0], 10),
    race: parseInt(parts[1], 10),
    subject: parseInt(parts[2], 10),
    posture: parseInt(parts[3], 10),
    homeworld: original ? Number(original[1] === 2) : parseInt(parts[4], 10),
    surrender: parseInt(parts[5], 10),
    text: parts.slice(6).join('|'),
    fileIndex: index,
    ...(original ? {postureMask:original[0],contextMask:original[1],action:original[2],deltaNo:original[3],deltaYes:original[4]} : {}),
  };
}

