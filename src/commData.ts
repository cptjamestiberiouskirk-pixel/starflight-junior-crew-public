export function resolveRaceId(race: string | number): number {
  if (typeof race === 'number') return race;
  const normalized = race.trim();
  if (ALIEN_RACE_TO_COMM_ID[normalized] !== undefined) {
    return ALIEN_RACE_TO_COMM_ID[normalized];
  }
  const lower = normalized.toLowerCase();
  for (const [key, val] of Object.entries(ALIEN_RACE_TO_COMM_ID)) {
    if (key.toLowerCase() === lower) return val;
  }
  const n = parseInt(normalized, 10);
  return !isNaN(n) ? n : 1;
}

export function resolveSubjectId(subject: string | number): number {
  if (typeof subject === 'number') return subject;
  const normalized = subject.trim().toLowerCase();
  if (COMM_SUBJECT_MAP[normalized] !== undefined) {
    return COMM_SUBJECT_MAP[normalized];
  }
  const n = parseInt(normalized, 10);
  return !isNaN(n) ? n : 5;
}

export function resolvePostureCode(
  posture?: string | number,
  mood?: number,
  isCowed?: boolean,
): number {
  if (isCowed) return 4;
  if (typeof posture === 'number') {
    if (posture >= 1 && posture <= 4) return posture;
  }
  if (typeof posture === 'string') {
    const p = posture.trim().toLowerCase();
    if (p === 'obsequious' || p === 'cowed' || p === 'grovelling' || p === 'groveling') return 4;
    if (p === 'hostile' || p === 'angry' || p === 'attacked') return 3;
    if (p === 'friendly' || p === 'pleased' || p === 'peaceful' || p === 'allied') return 2;
    if (p === 'neutral') return 1;
    const n = parseInt(p, 10);
    if (!isNaN(n) && n >= 1 && n <= 4) return n;
  }
  if (typeof mood === 'number') {
    if (mood >= 50) return 3;
    if (mood < 25) return 2;
    return 1;
  }
  return 1;
}

